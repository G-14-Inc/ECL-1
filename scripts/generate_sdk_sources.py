"""Generate the schema, registry and type sources that the TypeScript and Go libraries embed.

The libraries validate the same JSON Schemas and read the same registries as the reference, and
must not drift from them. This script copies the wire schemas (DCMP-2, EBMP-2, the integrity
envelope, the evidence bundle, the time attestation, the trust policy, the safe-state profile,
the adapter binding, the offline package manifest, the registered extension value schemas and
everything they reference), the
record schemas of the five binding profiles and the claim and assessment document schemas that
the conformance runner's `binding` and `document` stages name, and the registry entries the
verifiers read into generated source files, and derives TypeScript types from the schemas.
`--check` fails when a generated file differs from what this script would write;
Run `python3 scripts/generate_sdk_sources.py --check` to verify the generated files.

A schema keyword or format that the libraries' validators do not implement is refused here, so a
schema change that needs new validator code fails loudly instead of being half-checked.
"""

