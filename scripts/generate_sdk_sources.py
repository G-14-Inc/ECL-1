class GenerationError(ValueError):
    """A schema or registry that the libraries cannot embed faithfully."""


def read_json(path: Path) -> Any:
    return json.loads(path.read_bytes())


def schema_files(root: Path) -> dict[str, tuple[str, Any]]:
    """Every schema with an `$id`, by that `$id`: its repository path and its document."""
    found: dict[str, tuple[str, Any]] = {}
    for path in sorted((root / "schemas").glob("*.json")):
        document = read_json(path)
        identifier = document.get("$id") if isinstance(document, dict) else None
        if isinstance(identifier, str):
            if identifier in found:
                raise GenerationError(f"two schemas share the $id {identifier}")
            found[identifier] = (path.relative_to(root).as_posix(), document)
    return found


def subschemas(node: Any) -> Iterator[Any]:
    """The schemas directly inside a schema node."""
    if not isinstance(node, dict):
        return
    for keyword in SCHEMA_MAPS:
        value = node.get(keyword)
        if isinstance(value, dict):
            yield from value.values()
    for keyword in SCHEMA_VALUES:
        if keyword in node:
            yield node[keyword]
    for keyword in SCHEMA_LISTS:
        value = node.get(keyword)
        if isinstance(value, list):
            yield from value


def check_node(node: Any, where: str) -> None:
    """Refuse a keyword or format that the validators do not implement, and a `__proto__` key."""
    if isinstance(node, bool):
        return
    if not isinstance(node, dict):
        raise GenerationError(f"{where}: a schema is an object or a boolean")
    unknown = set(node) - VALIDATION_KEYWORDS - ANNOTATION_KEYWORDS
    if unknown:
        raise GenerationError(f"{where}: unsupported schema keywords {sorted(unknown)}")
    if "format" in node and node["format"] not in FORMATS:
        raise GenerationError(f"{where}: unsupported format {node['format']!r}")
    for child in subschemas(node):
        check_node(child, where)


def check_keys(value: Any, where: str) -> None:
    if isinstance(value, dict):
        if "__proto__" in value:
            raise GenerationError(f"{where}: a member named __proto__ cannot be embedded")
        for item in value.values():
            check_keys(item, where)
    elif isinstance(value, list):
        for item in value:
            check_keys(item, where)


def references(node: Any) -> Iterator[str]:
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                yield value
            elif key not in ("const", "enum", "default", "examples"):
                yield from references(value)
    elif isinstance(node, list):
        for item in node:
            yield from references(item)


def extension_value_schemas(root: Path) -> list[str]:
    entries = read_json(root / "registries/extensions.json")["entries"]
    found = []
    for entry in entries:
        schema = entry.get("attributes", {}).get("value_schema")
        if isinstance(schema, str):
            found.append(schema)
    return found


def selected_schemas(root: Path, *, records: bool = True) -> dict[str, tuple[str, Any]]:
    """The root schemas, the extension value schemas, and every schema they reference; with
    `records`, also the binding-record and document schemas and what they reference."""
    available = schema_files(root)
    pending = [*ROOTS, *extension_value_schemas(root), *(RECORD_ROOTS if records else ())]
    selected: dict[str, tuple[str, Any]] = {}
    while pending:
        identifier = pending.pop()
        if identifier in selected:
            continue
        if identifier not in available:
            raise GenerationError(f"no schema has the $id {identifier}")
        path, document = available[identifier]
        check_node(document, path)
        check_keys(document, path)
        selected[identifier] = (path, document)
        for reference in references(document):
            target = reference.split("#", 1)[0]
            if target and target not in selected:
                pending.append(target)
    return dict(sorted(selected.items()))


def registry_entries(root: Path) -> dict[str, list[dict[str, Any]]]:
    result: dict[str, list[dict[str, Any]]] = {}
    for name, fields in REGISTRY_FIELDS.items():
        entries = []
        for entry in read_json(root / "registries" / f"{name}.json")["entries"]:
            attributes = entry.get("attributes", {})
            row: dict[str, Any] = {"id": entry["id"], "status": entry["status"]}
            for field in fields:
                if field == "description" and isinstance(entry.get("description"), str):
                    row[field] = entry["description"]
                elif field in attributes:
                    row[field] = attributes[field]
            entries.append(row)
        result[name] = entries
    return result


def sources_digest(root: Path, paths: list[str]) -> str:
    digest = hashlib.sha256()
    for path in sorted(paths):
        digest.update(path.encode() + b"\0" + hashlib.sha256((root / path).read_bytes()).digest())
    return digest.hexdigest()


# --- TypeScript ----------------------------------------------------------------------------------


def pascal(text: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", text) if part)


def type_prefix(identifier: str) -> str:
    if identifier in ROOT_TYPE_NAMES:
        name = ROOT_TYPE_NAMES[identifier]
        return "Common" if identifier == NS + "common/1" else name
    path = identifier.removeprefix(NS).rsplit("/", 1)[0]
    if path.startswith("extension/"):
        return pascal(path.removeprefix("extension/")) + "Extension"
    return pascal(path)


def root_type_name(identifier: str) -> str:
    if identifier in ROOT_TYPE_NAMES:
        return ROOT_TYPE_NAMES[identifier]
    return type_prefix(identifier) + ("Value" if "/extension/" in identifier else "")


def def_type_name(identifier: str, name: str) -> str:
    prefix = type_prefix(identifier)
    if identifier == NS + "dcmp/2":
        prefix = "Dcmp"
    elif identifier == NS + "ebmp/2":
        prefix = "Ebmp"
    elif identifier == NS + "trust-policy/1":
        prefix = "TrustPolicy"
    return prefix + pascal(name)


def ts_literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def top_level(text: str, operator: str) -> bool:
    """Whether `operator` (" | " or " & ") occurs in `text` outside any bracket or string."""
    depth = 0
    quoted = False
    index = 0
    while index < len(text):
        character = text[index]
        if quoted:
            if character == "\\":
                index += 1
            elif character == '"':
                quoted = False
        elif character == '"':
            quoted = True
        elif character in "({[<":
            depth += 1
        elif character in ")}]>":
            depth -= 1
        elif depth == 0 and text.startswith(operator, index):
            return True
        index += 1
    return False


def wrap(text: str) -> str:
    return f"({text})" if top_level(text, " | ") or top_level(text, " & ") else text


def union(options: list[str]) -> str:
    unique = list(dict.fromkeys(options))
    if len(unique) == 1:
        return unique[0]
    return " | ".join(wrap(option) if top_level(option, " & ") else option for option in unique)


def ts_comment(node: Any, indent: str = "") -> list[str]:
    if not isinstance(node, dict):
        return []
    text = " ".join(
        str(node[key]).strip() for key in ("title", "description") if isinstance(node.get(key), str)
    )
    if not text:
        return []
    text = text.replace("*/", "* /")
    return [f"{indent}/** {text} */"]


class TypeWriter:
    """Producer shapes, not a replacement for runtime JSON Schema validation.

    String index signatures cannot exclude a finite set of declared names or express arbitrary
    JSON Schema property-name patterns. Their value union includes the declared property types
    so that a schema-valid named member is not made impossible by an additional-member type.
    """

    def __init__(self, schemas: dict[str, tuple[str, Any]]) -> None:
        self.schemas = schemas

    def ref_name(self, base: str, reference: str) -> str:
        target, _, fragment = reference.partition("#")
        identifier = target or base
        if identifier not in self.schemas:
            raise GenerationError(f"unresolved reference {reference}")
        if fragment in ("", "/"):
            return root_type_name(identifier)
        match = re.fullmatch(r"/\$defs/([^/]+)", fragment)
        if match is None:
            raise GenerationError(f"reference {reference} does not name a definition")
        return def_type_name(identifier, match.group(1))

    def expression(self, node: Any, base: str, indent: str) -> str:
        """A type expression for `node`, safe to place anywhere (unions are parenthesized only
        when they are combined)."""
        if node is True:
            return "JsonValue"
        if node is False:
            return "never"
        parts: list[str] = []
        if "$ref" in node:
            parts.append(self.ref_name(base, node["$ref"]))
        if "const" in node:
            parts.append(ts_literal(node["const"]))
        elif "enum" in node:
            parts.append(union([ts_literal(item) for item in node["enum"]]))
        elif "type" in node:
            types = node["type"] if isinstance(node["type"], list) else [node["type"]]
            parts.append(union([self.typed(kind, node, base, indent) for kind in types]))
        elif "properties" in node:
            parts.append(self.object(node, base, indent))
        parts.extend(self.expression(item, base, indent) for item in node.get("allOf", []))
        parts.extend(
            union([self.expression(item, base, indent) for item in node[keyword]])
            for keyword in ("anyOf", "oneOf")
            if keyword in node
        )
        parts = [part for part in parts if part != "JsonValue"] or ["JsonValue"]
        if len(parts) == 1:
            return parts[0]
        return " & ".join(wrap(part) for part in parts)

    def typed(self, kind: str, node: dict[str, Any], base: str, indent: str) -> str:
        if kind == "string":
            return "string"
        if kind in ("integer", "number"):
            return "number"
        if kind == "boolean":
            return "boolean"
        if kind == "null":
            return "null"
        if kind == "array":
            items = node.get("items", True)
            if "prefixItems" in node:
                prefix = node["prefixItems"]
                minimum = node.get("minItems", 0)
                maximum = node.get("maxItems")
                if maximum is not None:
                    prefix = prefix[:maximum]
                members = [self.expression(item, base, indent) for item in prefix]
                members = [part if i < minimum else "(" + part + ")?" for i, part in enumerate(members)]
                if items is not False and (maximum is None or maximum > len(prefix)):
                    members.append("...Array<" + self.expression(items, base, indent) + ">")
                return "[" + ", ".join(members) + "]"
            return "Array<" + self.expression(items, base, indent) + ">"
        if kind == "object":
            return self.object(node, base, indent)
        raise GenerationError(f"unknown type {kind}")

    def object(self, node: dict[str, Any], base: str, indent: str) -> str:
        properties = node.get("properties", {})
        additional = node.get("additionalProperties", True)
        patterns = node.get("patternProperties", {})
        extra_types = [self.expression(schema, base, indent) for schema in patterns.values()]
        if additional is not False:
            extra_types.append(self.expression(additional, base, indent))
        # A pattern may permit members even when additionalProperties is false. Its values can
        # be represented conservatively here; its actual key domain remains a runtime check.
        if not properties:
            if not extra_types:
                return "Record<string, never>"
            values = "JsonValue" if "JsonValue" in extra_types else union(extra_types)
            return "{ [member: string]: " + values + " }"
        required = set(node.get("required", []))
        inner = indent + "  "
        lines = ["{"]
        property_types: list[str] = []
        for name, schema in properties.items():
            lines.extend(ts_comment(schema, inner))
            optional = "" if name in required else "?"
            expression = self.expression(schema, base, inner)
            property_types.append(expression)
            lines.append(
                f"{inner}{json.dumps(name)}{optional}: {expression};"
            )
        lines.append(indent + "}")
        shape = "\n".join(lines)
        if extra_types:
            values = "JsonValue" if "JsonValue" in extra_types else union(extra_types + property_types)
            # Keep optional named fields outside the index signature. This preserves ordinary
            # optional-property access without admitting undefined as an extra JSON value.
            return shape + " & { [member: string]: " + values + " }"
        return shape

    def declarations(self) -> list[str]:
        owners = {"JsonValue": "the imported JSON value type"}
        for identifier, (path, document) in self.schemas.items():
            names = [(def_type_name(identifier, name), f"{path}#/$defs/{name}")
                     for name in document.get("$defs", {})]
            names.append((root_type_name(identifier), path))
            for name, origin in names:
                if name in owners:
                    raise GenerationError(f"duplicate TypeScript type name {name}: {owners[name]} and {origin}")
                owners[name] = origin
        lines: list[str] = []
        for identifier, (path, document) in self.schemas.items():
            lines.append(f"// {identifier} ({path})")
            for name, schema in document.get("$defs", {}).items():
                lines.extend(ts_comment(schema))
                lines.append(
                    f"export type {def_type_name(identifier, name)} = "
                    f"{self.expression(schema, identifier, '')};"
                )
            body = {key: value for key, value in document.items() if key != "$defs"}
            lines.extend(ts_comment(document))
            lines.append(
                f"export type {root_type_name(identifier)} = "
                f"{self.expression(body, identifier, '')};"
            )
            lines.append("")
        return lines


def schema_module(
    stamp: str, constant: str, summary: str, schemas: dict[str, tuple[str, Any]]
) -> bytes:
    lines = [
        stamp,
        'import type { JsonValue } from "../json/value.js";',
        "",
        f"/** {summary} */",
        f"export const {constant}: ReadonlyArray<readonly [string, JsonValue]> = [",
    ]
    for identifier, (_, document) in schemas.items():
        body = json.dumps(document, indent=2, ensure_ascii=False).replace("\n", "\n    ")
        lines.append(f"  [\n    {json.dumps(identifier)},\n    {body},\n  ],")
    lines.append("];")
    return ("\n".join(lines) + "\n").encode()


def typescript_sources(root: Path) -> dict[Path, bytes]:
    schemas = selected_schemas(root)
    wire = selected_schemas(root, records=False)
    records = {identifier: item for identifier, item in schemas.items() if identifier not in wire}
    registries = registry_entries(root)
    inputs = [path for path, _ in schemas.values()] + [
        f"registries/{name}.json" for name in REGISTRY_FIELDS
    ]
    stamp = f"// {HEADER}\n// Sources SHA-256: {sources_digest(root, inputs)}\n// Do not edit.\n"
    registry_lines = [
        stamp,
        "/** One registry entry, with the attributes the libraries read. */",
        "export interface RegistryEntry {",
        "  readonly id: string;",
        "  readonly status: string;",
        "  readonly precedence?: number;",
        "  readonly stage?: number;",
        "  readonly version?: number;",
        "  readonly value_schema?: string;",
        "  readonly composable_versions?: boolean;",
        "  readonly applies_to?: readonly string[];",
        "  readonly category?: string;",
        "  readonly kind?: string;",
        "  readonly description?: string;",
        "}",
        "",
    ]
    for name, entries in registries.items():
        constant = name.upper().replace("-", "_")
        registry_lines.append(f"/** registries/{name}.json */")
        registry_lines.append(f"export const {constant}: readonly RegistryEntry[] = [")
        registry_lines.extend(f"  {json.dumps(entry, ensure_ascii=False)}," for entry in entries)
        registry_lines.append("];")
        registry_lines.append("")
    types = TypeWriter(schemas)
    type_lines = [
        stamp,
        "// TypeScript types derived from the schemas. They describe the shapes; the schemas,",
        "// checked at run time by validateSchema, remain the authority on what is valid.",
        "// Open object index signatures conservatively include named member types. Exact extra",
        "// member constraints, property-name patterns and conditional rules need runtime validation.",
        "",
        'import type { JsonValue } from "../json/value.js";',
        "",
        *types.declarations(),
    ]
    return {
        TS_OUT / "schemas.ts": schema_module(
            stamp, "SCHEMA_DOCUMENTS", "The embedded schema documents, by `$id`.", wire
        ),
        TS_OUT / "record-schemas.ts": schema_module(
            stamp,
            "RECORD_SCHEMA_DOCUMENTS",
            "The binding-record and document schemas, by `$id`; they reference the wire schemas.",
            records,
        ),
        TS_OUT / "registries.ts": ("\n".join(registry_lines)).rstrip("\n").encode() + b"\n",
        TS_OUT / "types.ts": ("\n".join(type_lines)).rstrip("\n").encode() + b"\n",
    }


# --- Go ------------------------------------------------------------------------------------------


def go_sources(root: Path) -> dict[Path, bytes]:
    """JSON files that the Go module embeds with go:embed, and the Go file that embeds them."""
    schemas = selected_schemas(root)
    registries = registry_entries(root)
    inputs = [path for path, _ in schemas.values()] + [
        f"registries/{name}.json" for name in REGISTRY_FIELDS
    ]
    documents = {identifier: document for identifier, (_, document) in schemas.items()}
    source = "\n".join(
        [
            "// Code generated by scripts/generate_sdk_sources.py; DO NOT EDIT.",
            f"// {HEADER}",
            f"// Sources SHA-256: {sources_digest(root, inputs)}",
            "",
            "// Package generated embeds the ECL-1 wire schemas, the schemas they reference and",
            "// the registry entries that the Go library reads, copied from the repository's",
            "// schemas/ and registries/ directories.",
            "package generated",
            "",
            'import _ "embed"',
            "",
            "// Schemas is a JSON object of the embedded schema documents, by $id.",
            "//",
            "//go:embed schemas.json",
            "var Schemas []byte",
            "",
            "// Registries is a JSON object of registry entries by registry name, each entry with",
            "// its id, status and the attributes that the library reads.",
            "//",
            "//go:embed registries.json",
            "var Registries []byte",
        ]
    )
    return {
        GO_OUT / "schemas.json": (
            json.dumps(documents, indent=2, ensure_ascii=False) + "\n"
        ).encode(),
        GO_OUT / "registries.json": (
            json.dumps(registries, indent=2, ensure_ascii=False) + "\n"
        ).encode(),
        GO_OUT / "generated.go": (source + "\n").encode(),
    }


def build(root: Path = ROOT) -> dict[Path, bytes]:
    return {**typescript_sources(root), **go_sources(root)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        outputs = build(args.root)
        stale = [
            path.as_posix()
            for path, data in outputs.items()
            if not (args.root / path).is_file() or (args.root / path).read_bytes() != data
        ]
        if args.check:
            if stale:
                raise GenerationError("generated SDK sources are stale: " + ", ".join(stale))
        else:
            for path, data in outputs.items():
                (args.root / path).parent.mkdir(parents=True, exist_ok=True)
                (args.root / path).write_bytes(data)
    except (OSError, ValueError, KeyError) as error:
        print(f"SDK sources: {error}", file=sys.stderr)
        return 1
    print("SDK sources: " + ("current" if args.check else "written"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
