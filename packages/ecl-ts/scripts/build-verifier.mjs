#!/usr/bin/env node
/**
 * Build the browser verifier's script, web/verifier/verifier.js, from web/app.ts and the library
 * sources, and keep the style hash in the page's content security policy current.
 *
 *   node scripts/build-verifier.mjs [--check] [--repo-root DIR]
 *
 * esbuild bundles the TypeScript sources and the two @noble packages into one classic script (an
 * immediately invoked function) because browsers refuse module scripts on pages opened from
 * file://. The output is not minified, so it can be read and compared with the sources; module
 * path comments are relative to this package, so every checkout and clean export builds the same
 * bytes. The MIT notices of the bundled @noble packages are copied in full from their LICENSE
 * files. With --check nothing is written, and the script fails unless web/verifier/verifier.js
 * and the policy in web/verifier/index.html equal a fresh build.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MAX_BUNDLE_BYTES = 2 * 1024 * 1024;
const THIRD_PARTY = ["@noble/curves", "@noble/hashes"];
const ALLOWED_INPUT = /^(?:src\/|web\/|node_modules\/@noble\/(?:curves|hashes)\/)/;

function options(argv) {
  let check = false;
  let root = resolve(PACKAGE, "../..");
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--repo-root" && index + 1 < argv.length) {
      index += 1;
      root = resolve(argv[index]);
    } else {
      throw new Error(`usage: build-verifier.mjs [--check] [--repo-root DIR] (unexpected ${argument})`);
    }
  }
  return { check, root };
}

function notices() {
  const texts = new Map();
  const names = [];
  for (const name of THIRD_PARTY) {
    const directory = join(PACKAGE, "node_modules", name);
    const metadata = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
    if (metadata.license !== "MIT") {
      throw new Error(`${name} is not MIT-licensed: ${metadata.license}`);
    }
    names.push(`${name} ${metadata.version}`);
    const text = readFileSync(join(directory, "LICENSE"), "utf8").trim();
    texts.set(text, [...(texts.get(text) ?? []), name]);
  }
  const lines = [
    "ECL-1 browser verifier. Generated by packages/ecl-ts/scripts/build-verifier.mjs from",
    "packages/ecl-ts/web/app.ts and the library in packages/ecl-ts/src. Do not edit.",
    "Copyright 2026 G-14, Inc. Licensed under the Apache License, Version 2.0 (LICENSE at the",
    "repository root). G-14's patent pledge for implementations of ECL-1 is in PATENTS.md.",
    "Patents pending.",
    "",
    `This file also contains ${names.join(" and ")}, under the MIT License:`,
  ];
  for (const [text, packages] of texts) {
    lines.push("", `${packages.join(", ")}:`, "", ...text.split("\n"));
  }
  return `/*\n${lines.map((line) => (line === "" ? " *" : ` * ${line.replaceAll("*/", "* /")}`)).join("\n")}\n */`;
}

async function bundle() {
  const result = await build({
    absWorkingDir: PACKAGE,
    entryPoints: ["web/app.ts"],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    charset: "utf8",
    legalComments: "inline",
    minify: false,
    sourcemap: false,
    metafile: true,
    write: false,
    logLevel: "silent",
    banner: { js: notices() },
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!ALLOWED_INPUT.test(input)) {
      throw new Error(`the bundle would include ${input}; only the library, web/app.ts and @noble are allowed`);
    }
  }
  const [output] = result.outputFiles;
  if (output === undefined || result.outputFiles.length !== 1) {
    throw new Error("esbuild did not produce exactly one file");
  }
  if (output.contents.length > MAX_BUNDLE_BYTES) {
    throw new Error(`the bundle has ${output.contents.length} bytes, more than ${MAX_BUNDLE_BYTES}`);
  }
  return output.contents;
}

function withStyleHash(page) {
  const styles = [...page.matchAll(/<style>([\s\S]*?)<\/style>/g)];
  if (styles.length !== 1) {
    throw new Error("index.html must have exactly one <style> element");
  }
  const hash = createHash("sha256").update(styles[0][1], "utf8").digest("base64");
  const policies = [...page.matchAll(/style-src 'sha256-[A-Za-z0-9+/=]*'|style-src 'sha256-PENDING'/g)];
  if (policies.length !== 1) {
    throw new Error("index.html must have exactly one style-src hash in its content security policy");
  }
  return { hash, page: page.replace(policies[0][0], `style-src 'sha256-${hash}'`) };
}

async function main() {
  const { check, root } = options(process.argv.slice(2));
  const scriptPath = join(root, "web/verifier/verifier.js");
  const pagePath = join(root, "web/verifier/index.html");
  const script = await bundle();
  const currentPage = readFileSync(pagePath, "utf8");
  const { hash, page } = withStyleHash(currentPage);
  const summary = {
    script: "web/verifier/verifier.js",
    bytes: script.length,
    sha256: createHash("sha256").update(script).digest("hex"),
    style_sha256: hash,
  };
  if (check) {
    let committed;
    try {
      committed = readFileSync(scriptPath);
    } catch {
      committed = Buffer.alloc(0);
    }
    const problems = [];
    if (!committed.equals(Buffer.from(script))) {
      problems.push("web/verifier/verifier.js differs from a fresh build (run npm run verifier:build)");
    }
    if (page !== currentPage) {
      problems.push("the style hash in web/verifier/index.html is stale (run npm run verifier:build)");
    }
    if (problems.length > 0) {
      process.stderr.write(`${problems.join("\n")}\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`${JSON.stringify({ ...summary, current: true })}\n`);
    return;
  }
  writeFileSync(scriptPath, script);
  if (page !== currentPage) {
    writeFileSync(pagePath, page);
  }
  process.stdout.write(`${JSON.stringify(summary)}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 2;
});
